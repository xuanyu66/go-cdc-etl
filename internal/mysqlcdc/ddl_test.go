package mysqlcdc

import "testing"

func TestUnrelatedDDL(t *testing.T) {
	for _, test := range []struct {
		query, db string
		unrelated bool
	}{
		{"CREATE TABLE shop.e2e_control_1 (id BIGINT PRIMARY KEY)", "", true},
		{"DROP TABLE IF EXISTS `shop`.`e2e_control_1` /* generated by server */", "", true},
		{"ALTER TABLE scratch ADD COLUMN note VARCHAR(8)", "shop", true},
		{"TRUNCATE TABLE other.orders", "shop", true},
		{"CREATE INDEX idx ON other.orders(id)", "shop", true},
		{"CREATE DATABASE unrelated", "", true},
		{"DROP DATABASE unrelated", "", true},
		{"ALTER TABLE shop.orders ADD COLUMN note VARCHAR(8)", "", false},
		{"ALTER TABLE orders ADD COLUMN note VARCHAR(8)", "shop", false},
		{"DROP TABLE shop.scratch, shop.orders", "", false},
		{"RENAME TABLE shop.scratch TO shop.orders", "", false},
		{"RENAME TABLE shop.orders TO shop.scratch", "", false},
		{"CREATE TABLE shop.scratch LIKE shop.orders", "", false},
		{"DROP DATABASE shop", "", false},
		{"ALTER TABLE orders ADD COLUMN x INT", "", false},
		{"CREATE TABLE shop.scratch (id INT); DROP TABLE shop.orders", "", false},
		{"UPDATE shop.scratch SET id=1", "shop", false},
		{"not valid SQL", "", false},
	} {
		t.Run(test.query, func(t *testing.T) {
			if got := unrelatedDDL(test.query, test.db, []string{"shop.orders"}); got != test.unrelated {
				t.Fatalf("unrelated=%v, want %v", got, test.unrelated)
			}
		})
	}
}
